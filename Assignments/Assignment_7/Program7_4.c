////////////////////////////////////////////////////////////////////
//
// Fuction Name :  OddDisplay
// Description :   Print the pattern printing
// Input :         Integer
// Output :        Integer
// Author :        Sakshi Ashok Adale
// Date :          21/11/2025
//
////////////////////////////////////////////////////////////////////

void OddDisplay(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        if(iCnt % 2 != 0)
        {
            printf("%d\t",iCnt);
        }
    }
    printf("\n");
}
    

////////////////////////////////////////////////////////////////////
//
// Entry point Function for the application
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the number : ");
    scanf("%d",&iValue);

    OddDisplay(iValue);

    return 0;
}

