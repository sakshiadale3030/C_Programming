bool CheckNumberType(int iNo)
{
    if(iNo > 0)
    {
        printf("Number is positive");
    }
    else if(iNo < 0)
    {
        printf("Number is negative");
    }
    else
    {
        printf("Number is zero");
    }

}
////////////////////////////////////////////////////////////////////
//
// Entry point Function for the application
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number : ");
    scanf("%d",&iValue);

    CheckNumberType(iValue);

    return 0;
}

